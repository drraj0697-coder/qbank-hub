import assert from 'node:assert/strict';
import {createQuestionHistory,historyLabel} from '../app/question-history.mjs';
const questions=Array.from({length:101},(_,i)=>({id:String(i)}));
let calls=[],resolve;
const db={rpc(name,args){calls.push({name,args});return new Promise(r=>resolve=r);}};
const cache=createQuestionHistory(db,'owner');
assert.equal(calls.length,0);
const first=cache.load(questions,0),same=cache.load(questions,20);
assert.equal(calls.length,1);assert.equal(calls[0].args.p_question_ids.length,40);
cache.set('0',{correct_count:2,wrong_count:3});
resolve({data:questions.slice(0,40).map(q=>({question_id:q.id,correct_count:1,wrong_count:0}))});
await Promise.all([first,same]);assert.equal(historyLabel(cache.get('0')),'✅ Correct × 2 · ❌ Wrong × 3','late batch cannot overwrite newer saved outcome');
for(let i=0;i<40;i++)await cache.load(questions,i);
assert.equal(calls.length,1,'no question-by-question requests');
const next=cache.load(questions,40);assert.equal(calls.length,2);resolve({error:new Error('offline')});await next;
assert.equal(historyLabel(cache.get('40')),'History unavailable');await cache.load(questions,41);assert.equal(calls.length,2,'no render retry storm');
assert.equal(historyLabel(undefined),'');assert.equal(historyLabel({correct_count:0,wrong_count:0}),'✅ Correct × 0 · ❌ Wrong × 0');
const other=createQuestionHistory(db,'other');assert.equal(other.get('0'),undefined);
console.log('PASS: lazy batched history, 40 navigations/one request, inflight dedup, late response protection, no false zeros, account isolation');

